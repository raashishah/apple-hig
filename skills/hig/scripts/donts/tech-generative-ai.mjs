import { hit, blocksWithAttr } from "./shared.mjs";

function hasGenai(text) {
  return (
    /\bdata-generative\b/.test(text) ||
    /\bdata-genai\b/.test(text) ||
    /\bLanguageModelSession\b/.test(text) ||
    /\bSystemLanguageModel\b/.test(text) ||
    /\bImagePlaygroundView\b/.test(text) ||
    /\bFoundationModels\b/.test(text)
  );
}

function hasHumanAuthoredClaim(text) {
  return (
    /\bas a human\b/i.test(text) ||
    /\bauthored by a human\b/i.test(text) ||
    /\bwritten by a human\b/i.test(text) ||
    /\bhuman-authored\b/i.test(text)
  );
}

function hasAiDisclosure(text) {
  return (
    /\bAI-generated\b/i.test(text) ||
    /\bgenerated by AI\b/i.test(text) ||
    /\bdata-ai-disclosure\b/.test(text)
  );
}

function scanAiAsHuman(files) {
  const out = [];
  for (const f of files) {
    if (/data-ai-as-human/.test(f.text)) {
      out.push(hit(f.path, "ai content presented as human-authored"));
      continue;
    }
    if (!hasGenai(f.text)) continue;
    if (hasHumanAuthoredClaim(f.text) && !hasAiDisclosure(f.text)) {
      out.push(hit(f.path, "ai content presented as human-authored"));
    }
  }
  return out;
}

function applyAiAsHuman(text) {
  return text.replace(/\s*data-ai-as-human(?:="[^"]*")?/g, "");
}

function scanGenaiNoRevert(files) {
  const out = [];
  for (const f of files) {
    if (/data-genai-no-revert/.test(f.text)) {
      out.push(
        hit(f.path, "generated content with no way to dismiss, revert, or retry"),
      );
    }
  }
  return out;
}

function applyGenaiNoRevert(text) {
  return text.replace(/\s*data-genai-no-revert(?:="[^"]*")?/g, "");
}

function genaiRegions(text) {
  const regions = [];
  for (const block of blocksWithAttr(text, "data-generative")) regions.push(block.text);
  const apis = /\b(?:LanguageModelSession|SystemLanguageModel|ImagePlaygroundView|FoundationModels)\b/g;
  let found;
  while ((found = apis.exec(text))) regions.push(text.slice(found.index, found.index + 800));
  return regions;
}

function regionAutomatesHarm(region) {
  return (
    /<button\b[^>]*>\s*(?:Delete|Empty Trash|Purchase|Buy)\b/i.test(region) ||
    /\bButton\s*\(\s*"(?:Delete|Empty Trash|Purchase|Buy)\b/.test(region)
  );
}

function hasGenaiHarmCopy(text) {
  return (
    /automating destructive actions/i.test(text) ||
    /destructive action inside a generative feature/i.test(text)
  );
}

function scanGenaiHarm(files) {
  const out = [];
  for (const f of files) {
    if (/data-ga-harm(?![\w-])/.test(f.text)) {
      out.push(hit(f.path, "automating a destructive action inside a generative feature"));
      continue;
    }
    if (!hasGenai(f.text)) continue;
    const harm = genaiRegions(f.text).some(regionAutomatesHarm);
    if (harm || hasGenaiHarmCopy(f.text)) {
      out.push(hit(f.path, "automating a destructive action inside a generative feature"));
    }
  }
  return out;
}

function applyGenaiHarm(text) {
  return text.replace(/\s*data-ga-harm(?:="[^"]*")?(?![\w-])/g, "");
}

export const records = [
  {
    id: "ai-as-human",
    rewrite: "marker",
    scan: scanAiAsHuman,
    apply(text, file) {
      return applyAiAsHuman(text);
    },
  },
  {
    id: "genai-no-revert",
    rewrite: "marker",
    scan: scanGenaiNoRevert,
    apply(text, file) {
      return applyGenaiNoRevert(text);
    },
  },
  {
    id: "ga-harm",
    rewrite: "marker",
    scan: scanGenaiHarm,
    apply(text, file) {
      return applyGenaiHarm(text);
    },
  },
];
